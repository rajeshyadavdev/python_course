""" 
Syntax:
  tuple_name = value1, value2, value3

Explanation
  1. Tuple packing means storing multiple values together in a tuple.
  2. Python automatically packs comma-separated values into a tuple.
  3. Parentheses are optional, but recommended for readability.

"""

student = "Rajesh", 21, "Python"
print(student)       # ('Rajesh', 21, 'Python')
print(type(student)) # <class 'tuple'>



