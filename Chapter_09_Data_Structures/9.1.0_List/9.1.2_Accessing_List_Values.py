""" 
Syntax:
  list_name[index]
  
Explanation
  1. List items are accessed using index numbers.
  2. Python indexing starts from 0.
  3. Positive indexing starts from the left.
  4. Negative indexing starts from the right.


list_name:   ["Rajesh","Rakesh","Ramesh"]
+ve_index:      0         1         2
-ve_index:     -3        -2        -3
"""

students = ["Rajesh","Rakesh","Ramesh"]
print(students[0])  # Rajesh
print(students[1])  # Rakesh
print(students[-1]) # Ramesh

