""" 
None means no value or empty value. It is used when a variable exists, but it does not
currently store any actual value.
"""

result = None
print(result,type(result))
# None <class 'NoneType'>

# ● None is not 0. None is not an empty string.

# ● None is not False. None means no value.

''' 
0 => A number
"" => empty string
False => Boolean
None => No value



variable created => no actual value yet => use None
'''
student_name = None
print(student_name) # None

# Later, the variable can store a real value:

student_name = "Rajesh"
print(student_name) # Rajesh

# Important: None must start with capital N.  we must use None and don't use none


