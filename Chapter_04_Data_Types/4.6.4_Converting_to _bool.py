""" 
bool() converts a value into True or False.

"""

x = 1
y = 0

print(x,bool(x))
print(y,bool(y))
# 1 True
# 0 False

# Some simple conversions:
print(bool(1)) # True
print(bool(0))  # False
print(bool("Python")) # True
print(bool("")) # False

