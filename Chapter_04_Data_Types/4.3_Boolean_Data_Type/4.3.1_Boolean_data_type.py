""" 
Boolean is a data type that has only two possible values:
1. True  means 1
2. False means 0

Boolean type is written as: bool
"""

is_active = True
is_deleted = False

print(f"is_active:{is_active}, and data type:{type(is_active)}")
# is_active:True, and data type:<class 'bool'>

print(f"is_deleted:{is_deleted}, and data type:{type(is_deleted)}")
# is_deleted:False, and data type:<class 'bool'>

