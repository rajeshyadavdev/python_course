""" 
Indexing means accessing one character from a string. Python starts counting from 0 index.

"""
word = "python"
print(word[0]) # p
print(word[1]) # y

# For negative indexing, counting starts from the end.
''' 
String    : p   y   t   h   o   n
+ve index : 0   1   2   3   4   5
-ve index : -6  -5  -4  -3  -2  -1
'''
print(word[-1]) # n
print(word[-2]) # o

