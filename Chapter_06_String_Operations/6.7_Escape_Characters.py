""" 
Escape characters start with a backslash \ and help insert special characters inside strings.

Common escape characters:
-------------------------

\n  =>New line

\t  =>Tab space

\\  =>Backslash

\'  =>Single quote

\"  =>Double quote
"""

# \n => New line
print("Python\nProgramming")
''' 
Python
Programming
'''


# \t  =>Tab space
print("Python\tProgramming") # Python  Programming


# \\  =>Backslash
print("Python\\Programming") # Python\Programming


# \'  =>Single quote
print("Python\'programming") # Python'programming

# \"  =>Double quote
print("Python\"Programming") # Python"Programming
